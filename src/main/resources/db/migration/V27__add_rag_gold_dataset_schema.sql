-- 运营调查型 RAG 人工金标数据集：版本化、不可变、按 Workspace 隔离。
-- 与 rag_evaluation_run（动态评测历史）分离；生产质量门禁只能引用已发布/冻结的本表快照，
-- 不能再依赖 RagEvaluationFixtureFactory 按当前已发布文档即时生成题目。

CREATE TABLE rag_gold_dataset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id),
    organization_id BIGINT NOT NULL REFERENCES organization(id),
    dataset_key VARCHAR(80) NOT NULL,
    dataset_version VARCHAR(100) NOT NULL,
    split VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    source_corpus_version VARCHAR(100) NOT NULL,
    checksum VARCHAR(64),
    frozen_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,
    CONSTRAINT uq_rag_gold_dataset_version UNIQUE (workspace_id, dataset_key, dataset_version),
    CONSTRAINT ck_rag_gold_dataset_split CHECK (
        split IN ('DEVELOPMENT', 'VALIDATION', 'FROZEN')
    ),
    CONSTRAINT ck_rag_gold_dataset_status CHECK (
        status IN ('DRAFT', 'PUBLISHED', 'FROZEN')
    )
);

-- 列表与 Runner 先按 Workspace 收敛，再按 split/status 过滤已发布快照。
CREATE INDEX idx_rag_gold_dataset_workspace_status
    ON rag_gold_dataset (workspace_id, status, split, created_at DESC);

CREATE TABLE rag_gold_case (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id),
    dataset_id BIGINT NOT NULL REFERENCES rag_gold_dataset(id),
    case_key VARCHAR(120) NOT NULL,
    question_text TEXT NOT NULL,
    question_type VARCHAR(40) NOT NULL,
    difficulty VARCHAR(20) NOT NULL,
    should_refuse BOOLEAN NOT NULL DEFAULT FALSE,
    annotation_basis VARCHAR(500),
    reviewer VARCHAR(120),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_rag_gold_case_key UNIQUE (dataset_id, case_key),
    CONSTRAINT ck_rag_gold_case_question_type CHECK (
        question_type IN (
            'SINGLE_DOCUMENT_FACT', 'CROSS_DOCUMENT', 'VERSION_CONFLICT',
            'WORKSPACE_BOUNDARY', 'OPERATION_PROCESS', 'REFUSAL'
        )
    ),
    CONSTRAINT ck_rag_gold_case_difficulty CHECK (
        difficulty IN ('EASY', 'MEDIUM', 'HARD')
    )
);

CREATE INDEX idx_rag_gold_case_dataset
    ON rag_gold_case (dataset_id, sort_order, case_key);

CREATE TABLE rag_gold_case_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id),
    case_id BIGINT NOT NULL REFERENCES rag_gold_case(id) ON DELETE CASCADE,
    granularity VARCHAR(20) NOT NULL,
    document_public_id UUID NOT NULL,
    version_public_id UUID,
    chunk_public_id UUID,
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_rag_gold_case_evidence_granularity CHECK (
        granularity IN ('DOCUMENT', 'VERSION', 'CHUNK')
    )
);

CREATE INDEX idx_rag_gold_case_evidence_case
    ON rag_gold_case_evidence (case_id, workspace_id, sort_order);

CREATE TABLE rag_gold_case_assertion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id),
    case_id BIGINT NOT NULL REFERENCES rag_gold_case(id) ON DELETE CASCADE,
    assertion_type VARCHAR(20) NOT NULL,
    assertion_text TEXT NOT NULL,
    weight DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_rag_gold_case_assertion_type CHECK (
        assertion_type IN ('REQUIRED_FACT', 'FORBIDDEN_CLAIM')
    )
);

CREATE INDEX idx_rag_gold_case_assertion_case
    ON rag_gold_case_assertion (case_id, workspace_id, sort_order);
