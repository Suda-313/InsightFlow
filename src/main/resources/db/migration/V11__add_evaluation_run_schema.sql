-- 金标评测批次以 workspace_id 为强制隔离键：固定脱敏题集虽不读取真实业务数据，
-- 但评测基线代表某个工作区选择的模型和 Prompt 组合，跨工作区比较会混淆治理责任。
CREATE TABLE evaluation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id),
    dataset_version VARCHAR(100) NOT NULL,
    prompt_version VARCHAR(100) NOT NULL,
    model_name VARCHAR(120) NOT NULL,
    retrieval_version VARCHAR(100) NOT NULL,
    metrics_json JSONB NOT NULL,
    case_results_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 历史列表和基线选择始终先按工作区过滤再按最新批次排序，避免跨工作区扫描与泄露。
CREATE INDEX idx_evaluation_run_workspace_created
    ON evaluation_run(workspace_id, created_at DESC);
