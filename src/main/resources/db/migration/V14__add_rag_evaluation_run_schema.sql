-- RAG 专项评测与既有通用 Prompt 金标评测使用不同的评分口径和 JSON 结构，必须独立存储，
-- 不能复用 evaluation_run 后靠字符串判断类型，否则历史解析和回归比较会相互污染。
CREATE TABLE rag_evaluation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id),
    dataset_version VARCHAR(100) NOT NULL,
    prompt_version VARCHAR(100) NOT NULL,
    model_name VARCHAR(120) NOT NULL,
    retrieval_version VARCHAR(100) NOT NULL,
    metrics_json JSONB NOT NULL,
    case_results_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 所有历史查询先收敛到 Workspace；在 P4 引入成员权限后仍可在该索引之上附加授权过滤。
CREATE INDEX idx_rag_evaluation_run_workspace_created
    ON rag_evaluation_run(workspace_id, created_at DESC);
