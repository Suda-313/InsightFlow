package com.insightflow.security;

/**
 * 组织成员在 P4 中可执行的固定职责集合。
 *
 * <p>角色不允许由客户端自定义，也不放入 JWT；授权服务每次根据数据库成员关系读取该枚举，确保成员变更立即生效。</p>
 */
public enum MemberRole {

    /** 组织初始化、成员管理、全部工作区管理和处置撤销。 */
    OWNER,

    /** 调查、报告和提交纠错，不能改变处置状态。 */
    ANALYST,

    /** 在获授权的工作区执行确认、忽略、分派、关闭和撤销。 */
    OPERATOR,

    /** 仅查看看板、调查、报告和证据。 */
    VIEWER
}
