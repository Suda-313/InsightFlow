package com.insightflow.entity;

/**
 * 首版人工可确认的调查处置动作集合。
 *
 * <p>不提供任意 SQL、规则覆盖或外部系统写入动作：确认、忽略和关闭仅改变调查流程状态，原始 Alert、指标和证据快照均不可被此枚举修改。</p>
 */
public enum ProposalAction {

    /** 认可冻结证据足以支持后续报告和纠错候选。 */
    CONFIRM,

    /** 人工判断本次告警无需处置，但仍保留完整调查与审计历史。 */
    IGNORE,

    /** 已确认调查在人工处理完成后关闭，仍可通过撤销回到待复核。 */
    CLOSE
}
